<script>
$(function () {
    const LOAD_URL   = "{{ route('ajax.reports.hr.overtime') }}";
    const EXPORT_URL = "{{ route('reports.hr.overtime.export') }}";

    var chartInstance = null;

    var reportDT = $('#reportTable').DataTable({
        processing: true,
        columns: [
            { data: null, orderable: false, render: function(d,t,r,m){ return m.row+1; } },
            { data: 'staff_number' },
            { data: 'full_names' },
            { data: 'department' },
            { data: 'position' },
            { data: 'days_recorded' },
            { data: 'total_hours' },
            { data: 'overtime_hours', render: function(d){
                var val = parseFloat(d);
                var cls = val > 0 ? 'text-warning fw-semibold' : '';
                return '<span class="' + cls + '">' + d + '</span>';
            }},
            { data: 'short_days', render: function(d){
                var cls = parseInt(d) > 0 ? 'text-danger fw-semibold' : '';
                return '<span class="' + cls + '">' + d + '</span>';
            }},
        ],
        order: [],
        pageLength: 25,
        lengthMenu: [[10, 25, 50, 100, -1], [10, 25, 50, 100, 'All']],
        language: { emptyTable: 'Apply filters and click Load Report.' }
    });

    $('#filterForm').on('submit', function (e) {
        e.preventDefault();
        var $btn = $('#loadBtn').prop('disabled', true)
                               .html('<span class="spinner-border spinner-border-sm me-1"></span> Loading...');
        $.ajax({
            url: LOAD_URL,
            type: 'POST',
            data: $(this).serialize(),
            success: function (res) {
                if (!res.success) { toastr.error(res.message || 'Failed to load report'); return; }
                reportDT.clear().rows.add(res.data).draw();
                $('#resultsInfo').text(res.count + ' record(s) found');
                $('#exportBtn').prop('disabled', false);

                // Render chart
                if (res.chart && Object.keys(res.chart).length > 0) {
                    $('#chartSection').show();
                    var labels = Object.keys(res.chart);
                    var values = Object.values(res.chart);
                    var ctx = document.getElementById('overtimeChart').getContext('2d');
                    if (chartInstance) { chartInstance.destroy(); }
                    chartInstance = new Chart(ctx, {
                        type: 'bar',
                        data: {
                            labels: labels,
                            datasets: [{
                                label: 'Overtime Hours',
                                data: values,
                                backgroundColor: 'rgba(255, 193, 7, 0.7)',
                                borderColor: 'rgba(255, 193, 7, 1)',
                                borderWidth: 1
                            }]
                        },
                        options: {
                            responsive: true,
                            plugins: { legend: { display: false } },
                            scales: { y: { beginAtZero: true, title: { display: true, text: 'Hours' } } }
                        }
                    });
                } else {
                    $('#chartSection').hide();
                }
            },
            error: function () { toastr.error('Failed to load report'); },
            complete: function () {
                $btn.prop('disabled', false)
                    .html('<span class="material-symbols-outlined align-middle" style="font-size:14px;">refresh</span> Load Report');
            }
        });
    });

    $('#exportBtn').on('click', function () {
        var $form = $('<form>', { method: 'POST', action: EXPORT_URL });
        $form.append($('#filterForm').find('input, select').clone());
        $('body').append($form);
        $form.submit();
        $form.remove();
    });
});
</script>
