<script>
    $(document).ready(function() {
        // Load returns data
        let table = $('#returns-table').DataTable({
            processing: true,
            ajax: {
                url: '/ajax/returns/batches/{{ encrypt($batch->id) }}/returns',
                dataSrc: 'data'
            },
            columns: [{
                    data: null,
                    render: function(data, type, row, meta) {
                        return meta.row + 1;
                    }
                },
                {
                    data: 'tenant_name',
                    render: function(data, type, row) {
                        return `<a href="javascript:void(0);" class="view-invoice-history proprty-link" 
                                   data-lease-id="${row.lease_id}" 
                                   data-tenant-name="${data}" 
                                   data-row-id="${row.id}">
                                   <span class="icon-space" style="display:inline-block;width:14px;"></span>${data}
                                </a>`;
                    }
                },
                {
                    data: 'trans_amount',
                    className: 'text-end'
                },
                {
                    data: 'comm_amount',
                    className: 'text-end'
                },
                {
                    data: 'vat_amount',
                    className: 'text-end'
                },
                {
                    data: 'payable_amount',
                    className: 'text-end'
                },
                {
                    data: 'abstract_threshold',
                    className: 'text-center',
                    render: function(data) {
                        return (parseFloat(data) || 0).toFixed(2) + '%';
                    }
                },
                {
                    data: 'approval_status',
                    className: 'text-center',
                    render: function(data) {
                        return data == 1 ? 'Approved' : 'Pending';
                    }
                }
            ],
            order: [
                [1, 'asc']
            ],
            pageLength: 25
        });

        // Handle click on tenant name to show invoice history
        $('#returns-table').on('click', '.view-invoice-history', function() {
            const leaseId = $(this).data('lease-id');
            const tenantName = $(this).data('tenant-name');
            const rowId = $(this).data('row-id');
            const $link = $(this);

            // Show spinner in the reserved icon space
            const originalHtml = $link.html();
            const tenantNameText = $link.contents().filter(function() {
                return this.nodeType === 3;
            }).text();
            $link.html('<span class="spinner-border spinner-border-sm" role="status" style="width:14px;height:14px;"></span>' + tenantNameText);
            $link.addClass('disabled');

            // Set modal title
            $('#modalTenantName').text(tenantName);

            // Show modal
            $('#invoiceHistoryModal').modal('show');

            // Show loader in modal
            $('#invoiceHistoryLoader').show();
            $('#invoiceHistoryContent').hide();

            // Fetch invoice history
            $.ajax({
                url: '/ajax/returns/invoice-history/' + leaseId,
                method: 'GET',
                data: {
                    batch_number: '{{ $batch->batch_number }}'
                },
                success: function(response) {
                    // Hide loader
                    $('#invoiceHistoryLoader').hide();

                    if (response.success && response.data.length > 0) {
                        let tableBody = '';

                        response.data.forEach(function(invoice) {
                            const commisionableAmt = parseFloat(invoice.commisionable_amount) || 0;
                            const payableAmt = parseFloat(invoice.payable_amount) || 0;
                            const currentBalance = parseFloat(invoice.current_balance) || 0;

                            // Calculate paid percentage
                            const baseAmount = commisionableAmt > 0 ? commisionableAmt : payableAmt;
                            const paidPct = baseAmount > 0 ? ((baseAmount - currentBalance) / baseAmount * 100) : 0;
                            const paidPctCapped = Math.min(Math.max(paidPct, 0), 100);

                            // Balance color: red if > 0, blue if 0
                            const balanceColor = currentBalance > 0 ? 'color: red;' : 'color: #3598db;';

                            tableBody += `
                                <tr>
                                    <td class="py-1 px-2" style="font-weight: bold; color: #3598db;">${invoice.date_due}</td>
                                    <td class="py-1 px-2">${invoice.item_name}</td>
                                    <td class="py-1 px-2">${invoice.advance_payable}</td>
                                    <td class="text-end py-1 px-2">${commisionableAmt.toLocaleString('en-US', {minimumFractionDigits: 2, maximumFractionDigits: 2})}</td>
                                    <td class="text-end py-1 px-2">${payableAmt.toLocaleString('en-US', {minimumFractionDigits: 2, maximumFractionDigits: 2})}</td>
                                    <td class="text-end py-1 px-2" style="font-weight: bold; ${balanceColor}">${currentBalance.toLocaleString('en-US', {minimumFractionDigits: 2, maximumFractionDigits: 2})}</td>
                                    <td class="text-end py-1 px-2">${paidPctCapped.toFixed(2)}%</td>
                                </tr>
                            `;
                        });

                        // Update table
                        $('#invoiceHistoryTableBody').html(tableBody);
                        $('#invoiceHistoryContent').show();
                    } else {
                        $('#invoiceHistoryContent').html('<p class="text-center text-muted small mb-0">No invoice history found for this lease.</p>');
                        $('#invoiceHistoryContent').show();
                    }

                    // Restore link
                    $link.html(originalHtml);
                    $link.removeClass('disabled');
                },
                error: function(xhr) {
                    $('#invoiceHistoryLoader').hide();
                    $('#invoiceHistoryContent').html('<p class="text-center text-danger">Error loading invoice history. Please try again.</p>');
                    $('#invoiceHistoryContent').show();

                    // Restore link
                    $link.html(originalHtml);
                    $link.removeClass('disabled');
                }
            });
        });

        // Reset modal content when closed
        $('#invoiceHistoryModal').on('hidden.bs.modal', function() {
            $('#invoiceHistoryLoader').show();
            $('#invoiceHistoryContent').hide();
            $('#invoiceHistoryTableBody').html('');
        });

        // Copy invoice history table to clipboard
        $('#copyInvoiceHistoryBtn').on('click', function() {
            const $btn = $(this);
            const $icon = $btn.find('i');
            const table = document.getElementById('invoiceHistoryTable');

            if (!table) {
                alert('No data to copy');
                return;
            }

            // Build text representation of table
            let text = 'Date\tItem\tAdvance\tComm Amt\tPay Amt\tBal\tPaid %\n';

            const rows = table.querySelectorAll('tbody tr');
            rows.forEach(row => {
                const cells = row.querySelectorAll('td');
                const rowData = Array.from(cells).map(cell => cell.innerText.trim()).join('\t');
                text += rowData + '\n';
            });

            // Copy to clipboard
            navigator.clipboard.writeText(text).then(() => {
                // Show success feedback
                $icon.removeClass('fa-copy').addClass('fa-check');
                $btn.html('<i class="fa fa-check"></i> Copied!');
                $btn.removeClass('btn-light').addClass('btn-primary');
                $btn.css({
                    'background-color': '#3598db !important',
                    'color': 'white !important',
                    'border-color': '#3598db !important'
                });
                $btn.attr('style', 'background-color: #3598db !important; color: white !important; border-color: #3598db !important;');

                // Reset button after 2 seconds
                setTimeout(() => {
                    $icon.removeClass('fa-check').addClass('fa-copy');
                    $btn.html('<i class="fa fa-copy"></i> Copy');
                    $btn.removeClass('btn-primary').addClass('btn-light');
                    $btn.removeAttr('style');
                }, 2000);
            }).catch(err => {
                alert('Failed to copy to clipboard');
                console.error('Copy failed:', err);
            });
        });

        // Load approvals when Approvals tab is clicked
        $('#approvals-tab').on('shown.bs.tab', function(e) {
            loadApprovalsTimeline();
        });

        // Load approvals timeline
        function loadApprovalsTimeline() {
            $('#approvals-loader').show();
            $('#approvals-main-content').hide();

            $.ajax({
                url: '/ajax/returns/batches/{{ encrypt($batch->id) }}/approvals',
                method: 'GET',
                success: function(response) {
                    $('#approvals-loader').hide();

                    if (response.success) {
                        const data = response.data;

                        // Render compact timeline (right column)
                        renderCompactTimeline(data.timeline, data.approval_item);

                        // Render conversation trail (left column)
                        renderCommentsTrail(data.timeline, data.approval_item, data.can_approve);

                        // Show action buttons if user can approve
                        if (data.can_approve) {
                            $('#action-buttons-section').show();
                            $('#waiting-message').remove();

                            // Show reject button only if can_reject is true
                            if (data.can_reject) {
                                $('#reject-btn').show();

                                // Populate return-to-level dropdown
                                const $select = $('#return-to-level');
                                $select.empty();
                                $select.append('<option value="">-- Select Level --</option>');

                                if (data.available_reject_levels && data.available_reject_levels.length > 0) {
                                    data.available_reject_levels.forEach(function(level) {
                                        $select.append('<option value="' + level.level + '">Level ' + level.level + ' - ' + escapeHtml(level.approver_name) + '</option>');
                                    });
                                }
                            } else {
                                $('#reject-btn').hide();
                            }
                        } else {
                            $('#action-buttons-section').hide();
                            $('#waiting-message').remove();
                            if (data.waiting_for_previous && data.waiting_message) {
                                $('#comments-trail').after('<div id="waiting-message" class="alert alert-info mt-2 py-2" style="font-size:0.78rem;"><i class="fa fa-hourglass-half me-2"></i>' + escapeHtml(data.waiting_message) + '</div>');
                            }
                        }

                        $('#approvals-main-content').show();
                    } else {
                        $('#approvals-timeline').html(
                            '<div class="alert alert-warning">' +
                            '<i class="fa fa-info-circle me-2"></i>' + response.message +
                            '</div>'
                        ).show();
                    }
                },
                error: function(xhr) {
                    $('#approvals-loader').hide();
                    $('#approvals-timeline').html(
                        '<div class="alert alert-danger">' +
                        '<i class="fa fa-exclamation-circle me-2"></i>Failed to load approval workflow. Please try again.' +
                        '</div>'
                    ).show();
                }
            });
        }

        // Render compact timeline (right column - col-4)
        function renderCompactTimeline(timeline, approvalItem) {
            let html = '<div class="timeline-steps" style="position: relative;">';

            timeline.forEach((item, index) => {
                // Determine status icon
                let statusIcon = '';
                let statusColor = '#6c757d';

                // Check if any action is Approved
                const hasApproved = item.actions && item.actions.some(a => a.action === 'Approved');
                // Check if any action is Returned or Rejected
                const hasReturned = item.actions && item.actions.some(a => a.action === 'Returned' || a.action === 'Rejected');

                if (hasApproved) {
                    statusIcon = '<i class="fa fa-check-circle" style="color: #28a745; font-size: 1.2rem;"></i>';
                    statusColor = '#28a745';
                } else if (hasReturned) {
                    statusIcon = '<i class="fa fa-times-circle" style="color: #dc3545; font-size: 1.2rem;"></i>';
                    statusColor = '#dc3545';
                } else if (item.status === 'Pending') {
                    statusIcon = '<i class="fa fa-clock" style="color: #ffc107; font-size: 1.2rem;"></i>';
                    statusColor = '#ffc107';
                } else {
                    statusIcon = '<i class="fa fa-circle" style="color: #dee2e6; font-size: 1.2rem;"></i>';
                    statusColor = '#dee2e6';
                }

                html += '<div class="timeline-step d-flex align-items-start mb-3" style="position: relative;">';

                // Icon column
                html += '<div class="me-3" style="min-width: 30px; text-align: center;">';
                html += statusIcon;

                // Add connecting line (except for last item)
                if (index < timeline.length - 1) {
                    html += '<div style="width: 2px; height: 40px; background: #dee2e6; margin: 4px auto 0;"></div>';
                }
                html += '</div>';

                // Content column
                html += '<div class="flex-grow-1">';
                html += '<div style="font-size: 0.875rem; font-weight: 600; color: #495057; margin-bottom: 2px;">Level ' + item.level + ' - ' + escapeHtml(item.approver_name) + '</div>';

                // Show all actions for this level
                if (item.actions && item.actions.length > 0) {
                    item.actions.forEach(function(action, actionIndex) {
                        html += '<div style="font-size: 0.75rem; color: #6c757d;">';
                        html += escapeHtml(action.action) + ' - ' + formatDate(action.action_timestamp);
                        if (action.sequence_number) {
                            html += ' | Cycle: ' + action.sequence_number;
                        }
                        html += '</div>';

                        // If returned, show return-to level
                        if (action.action === 'Returned' && action.returned_to_level) {
                            html += '<div style="font-size: 0.75rem; color: #dc3545;">Returned to Level ' + action.returned_to_level + '</div>';
                        }
                    });
                }

                html += '</div>'; // flex-grow-1
                html += '</div>'; // timeline-step
            });

            html += '</div>'; // timeline-steps

            $('#compact-timeline').html(html);
        }

        // Render conversation-style comments trail (left column - col-8)
        function renderCommentsTrail(timeline, approvalItem, canApprove) {
            let html = '';

            // Collect all actions from all levels and sort by timestamp
            let allActions = [];
            timeline.forEach((item) => {
                if (item.actions && item.actions.length > 0) {
                    item.actions.forEach(function(action) {
                        allActions.push({
                            level: item.level,
                            approver_name: item.approver_name,
                            is_user: item.is_user,
                            action: action.action,
                            comments: action.comments,
                            action_timestamp: action.action_timestamp,
                            sequence_number: action.sequence_number,
                            returned_to_level: action.returned_to_level
                        });
                    });
                }
            });

            // Sort by timestamp ascending (oldest first)
            allActions.sort((a, b) => new Date(a.action_timestamp) - new Date(b.action_timestamp));

            // Render as simple conversation thread - all in one card
            if (allActions.length === 0) {
                html += '<div class="text-center text-muted py-4">';
                html += '<i class="fa fa-info-circle fa-2x mb-2"></i>';
                html += '<p>No actions yet</p>';
                html += '</div>';
            } else {
                allActions.forEach((action, index) => {
                    // Add separator between comments (except for first one)
                    if (index > 0) {
                        html += '<hr style="margin: 12px 0; border: 0; border-top: 1px solid #e9ecef;">';
                    }

                    // Two column layout: Left (avatar + name) and Right (time, level, comment)
                    html += '<div class="row">';

                    // Left column: Avatar and Name
                    html += '<div class="col-3">';
                    html += '<div class="d-flex align-items-start">';
                    // Avatar/Profile icon - bluish, smaller
                    html += '<div class="me-2" style="min-width: 24px;">';
                    html += '<div style="width: 24px; height: 24px; border-radius: 50%; background: #d6ebf7; display: flex; align-items: center; justify-content: center;">';
                    html += '<i class="fa fa-user" style="color: #3598db; font-size: 0.7rem;"></i>';
                    html += '</div>';
                    html += '</div>';
                    // Name
                    html += '<div>';
                    html += '<span style="font-size: 0.8rem; font-weight: 600; color: #212529; line-height: 1.2;">' + escapeHtml(action.approver_name).toUpperCase() + '</span>';
                    html += '</div>';
                    html += '</div>'; // d-flex
                    html += '</div>'; // col-3

                    // Right column: Time, Level/Cycle, and Comment
                    html += '<div class="col-9">';

                    // Determine icon based on action type
                    let actionIcon = '';
                    let iconColor = '';
                    if (action.action === 'Approved') {
                        actionIcon = '<i class="fa fa-check-circle" style="color: #28a745; font-size: 0.75rem;"></i>';
                        iconColor = '#28a745';
                    } else if (action.action === 'Returned' || action.action === 'Rejected') {
                        actionIcon = '<i class="fa fa-times-circle" style="color: #dc3545; font-size: 0.75rem;"></i>';
                        iconColor = '#dc3545';
                    } else if (action.action === 'Initiated') {
                        actionIcon = '<i class="fa fa-play-circle" style="color: #3598db; font-size: 0.75rem;"></i>';
                        iconColor = '#3598db';
                    }

                    // Time and Level/Cycle with icon
                    html += '<div style="margin-bottom: 6px;">';
                    if (actionIcon) {
                        html += actionIcon + ' ';
                    }
                    html += '<span style="font-size: 0.65rem; color: #3598db; font-style: italic;">';
                    html += formatDate(action.action_timestamp) + ' • L' + action.level;
                    if (action.sequence_number) {
                        html += 'C' + action.sequence_number;
                    }
                    html += '</span>';
                    html += '</div>';

                    // Comment text
                    if (action.comments) {
                        html += '<div style="font-size: 0.9rem; color: #495057; line-height: 1.5;">';
                        html += escapeHtml(action.comments);
                        html += '</div>';
                    } else {
                        html += '<div style="font-size: 0.9rem; color: #6c757d; font-style: italic;">';
                        html += action.action;
                        if (action.returned_to_level) {
                            html += ' to Level ' + action.returned_to_level;
                        }
                        html += '</div>';
                    }

                    html += '</div>'; // col-9
                    html += '</div>'; // row
                });
            }

            $('#comments-trail').html(html);
        }

