-- ============================================================================
-- 1. cb_money_recoveries  (CHRACT, 221,468 rows)
-- ============================================================================
-- Returns account transactions from CHABRINS CHRACT table.
-- Both CREDIT entries (rent/charges collected for landlord) and
-- DEBIT/DEDUCTION entries (recoveries deducted from landlord:
-- SAT DEPOSIT, PAID OWNER, ABSCONDED, OVERPAID, PAID VACANT).
--
-- TRACLASS = CR (218,213 credits) | DR (3,255 deductions/recoveries).
-- Links to cb_returns_summary via return_id (CHRHMS.RETURNID = CHRACT.RETNPRD).
-- ============================================================================

create table cb_money_recoveries (
    id                      bigint generated by default as identity primary key,
    transaction_number      varchar(10),                -- GTTCNUM: unique transaction ref
    property_id             int not null,               -- FK to sys_pm_properties (from BLOCKID)
    client_id               int,                        -- FK to sys_pm_clients (from LORDID)
    unit_id                 int,                        -- FK to sys_pm_units (from BLOCKID+UNITNO)
    tenant_id               int,                        -- FK to sys_pm_clients (tenant)
    return_id               int,                        -- FK to cb_returns_summary (from RETNPRD)
    zone_id                 int,                        -- FK to sys_set_zones
    field_officer_id        int,                        -- FK to josya_users
    zone_supervisor_id      int,                        -- FK to josya_users
    zone_manager_id         int,                        -- FK to josya_users

    unit_code               varchar(30),                -- UNITNO: original unit code
    year                    int not null,               -- ACYEAR: accounting year
    month                   int not null,               -- ACMNTH: accounting month
    return_period           varchar(50),                -- RETNPRD: e.g. 202601
    return_type             varchar(50),                -- RTYPE: return type code
    tenant_name             varchar(50),                -- TENNAME: tenant name
    tenant_status           varchar(50),                -- TENSTAT: Normal, Caretaker, etc.

    transaction_type        varchar(20),                -- TRATYPE: RENT CURRENT, DEDUCTION, etc.
    transaction_category    varchar(50),                -- TRACATEG: RENT, WABILL, Recovery, etc.
    transaction_class       varchar(20),                -- TRACLASS: CR or DR
    transaction_source      varchar(70),                -- TRASRC: Unsupported Payment, etc.
    payment_mode            varchar(20),                -- PYMOD: CA (cash), REC (recovery), NULL
    transaction_ref         varchar(100),               -- TRANSREF: reference text
    transaction_date        varchar(50),                -- TRANSDAT: date string
    transaction_description varchar(50),                -- TRANSDESC: e.g. SAT DEPOSIT, RENT FOR ...

    amount_payable          numeric(18,2) default 0,    -- AMTPAYBL: amount payable to landlord
    debit_amount            numeric(18,2) default 0,    -- AMTDR: deduction/recovery amount
    credit_amount           numeric(18,2) default 0,    -- AMTCR: credit amount
    return_period_num       int,                        -- RPERIOD: return period as integer
    payment_period_num      int,                        -- PPERIOD: payment period as integer
    prorate_rate            numeric(18,2) default 0,    -- PRRATE: prorate rate
    amount_returned         numeric(18,2) default 0,    -- AMTRETRN: amount returned
    balance_amount          numeric(18,2) default 0,    -- AMTBAL: balance amount

    is_vatable              boolean default false,      -- VATABL: Yes/No
    is_commissionable       boolean default false,      -- COMMBL: Yes/No
    deduction_point_2       varchar(50),                -- DEDPNT2

    processing_status       smallint default 0,         -- PLSTATUS
    record_status           smallint default 1,         -- RSTATUS: 1=active
    is_locked               boolean default true,       -- LOCKD: 1=locked

    created_at              timestamp default now(),
    updated_at              timestamp default now()
);

create index idx_cb_money_recoveries_property    on cb_money_recoveries (property_id);
create index idx_cb_money_recoveries_client      on cb_money_recoveries (client_id);
create index idx_cb_money_recoveries_return      on cb_money_recoveries (return_id);
create index idx_cb_money_recoveries_year_month  on cb_money_recoveries (year, month);
create index idx_cb_money_recoveries_class       on cb_money_recoveries (transaction_class);


