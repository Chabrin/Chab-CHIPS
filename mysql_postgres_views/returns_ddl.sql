-- ============================================================================
-- PostgreSQL DDL: returns & landlord account tables
-- ============================================================================
-- These three tables capture the full returns lifecycle from CHABRINS:
--
-- Source: CHRHMS  -> cb_returns_summary    (return header — one per property per period)
-- Source: CHRTXS  -> cb_returns_clients    (return detail lines — per unit/tenant charges)
-- Source: CHLACC  -> cb_landlord_account   (landlord account ledger — debits/credits)
--
-- Flow: Returns are prepared per property per month (cb_returns_summary).
--       Each return has detail charge lines per unit/tenant (cb_returns_clients).
--       Once finalized/approved, entries post to the landlord account (cb_landlord_account).
--
-- Run on: chips_db_v3 (PostgreSQL)
-- ============================================================================


-- ============================================================================
-- 1. cb_returns_summary  (source: CHRHMS — 35,217 rows)
-- ============================================================================
-- Each row is a return header for one property for one period (month/year).
-- Tracks preparation → checking → finalization → approval → payment workflow.
-- Financial totals are aggregated from the detail lines (cb_returns_clients).

create table cb_returns_summary (
    id                    bigint generated by default as identity primary key,
    return_code           varchar(50) not null,      -- RETURNID: unique return identifier
    landlord_code         varchar(20) not null,      -- LORDID: landlord code
    property_code         varchar(20),               -- BLOCKID: property/block code
    year                  int not null,              -- YEARR: return year
    month                 int not null,              -- MONTHH: return month
    return_description    varchar(100),              -- RETDESC: return description
    return_period         varchar(6),                -- RETNPRD: period code (YYYYMM)
    return_type           varchar(50),               -- RETTYPE: return type
    commission_rate       numeric(18,2) default 0,   -- COMMRATE: commission rate %
    total_credit          numeric(18,2) default 0,   -- TOTALCR: total credit (collections)
    commission_total      numeric(18,2) default 0,   -- SUMCOM: sum of commissionable amounts
    vatable_total         numeric(18,2) default 0,   -- SUMVATBL: sum of VAT-able amounts
    commission_amount     numeric(18,2) default 0,   -- TOTALCOM: total commission charged
    total_debit           numeric(18,2) default 0,   -- TOTALDR: total debit (deductions)
    net_amount            numeric(18,2) default 0,   -- NETAMT: net amount
    transaction_amount    numeric(18,2) default 0,   -- TRXAMT: transaction amount
    net_balance           numeric(18,2) default 0,   -- NETBAL: net balance
    prepared_by           varchar(50),               -- PREPBY: prepared by (staff)
    prepared_status       int default 0,             -- PREPST: preparation status (0/1)
    prepared_date         timestamp,                 -- PREPDAT: preparation date
    checked_by            varchar(50),               -- CHKBY: checked by (staff)
    checked_status        int default 0,             -- CHKST: check status (0/1)
    checked_date          timestamp,                 -- CHKDAT: check date
    saved_status          int default 0,             -- SAVDST: saved status
    finalized_status      int default 0,             -- FINAST: finalization status (0/1)
    finalized_by          varchar(50),               -- FINABY: finalized by (staff)
    finalized_date        timestamp,                 -- FINADAT: finalization date
    approved_by           varchar(50),               -- APPBY: approved by (staff)
    approved_status       int default 0,             -- APPST: approval status (0/1)
    approved_date         timestamp,                 -- APPDAT: approval date
    paid_status           int default 0,             -- PAIDST: paid out status (0/1)
    voucher_number        varchar(50),               -- VOUCHERNO: payment voucher number
    remarks               varchar(50),               -- RETRMKS: return remarks
    remarks_2             varchar(50),               -- RETRMKS2: additional remarks
    rebate_year           int,                       -- REBYRR: rebate year
    rebate_month          int,                       -- REBMNTH: rebate month
    return_tag            varchar(2),                -- RETURNT: return tag
    return_status         int default 0,             -- RETSTAT: return status (0=pending, 1=processed)
    cheque_number         varchar(50),               -- CHQNO: cheque number
    bank_account          varchar(50),               -- BANKACC: bank account
    amount_paid           numeric(18,2) default 0,   -- AMTPAYD: amount paid out
    amount_overdraft      numeric(18,2) default 0,   -- AMTOVD: overdraft amount
    payment_date          varchar(30),               -- PAYDAT: payment date (varchar in source)
    return_zone           varchar(2),                -- RETZON: zone code
    auth_2m               int default 0,             -- AUTH2M: authorization flag
    auth_un               int default 0,             -- AUTHUN: authorization flag
    overdraft_percentage  numeric(18,3) default 0,   -- OVDPER: overdraft percentage
    return_id             int                        -- PRE-STAMPED: return_id FK
);

create unique index idx_cb_returns_summary_code   on cb_returns_summary (return_code);
create index idx_cb_returns_summary_landlord      on cb_returns_summary (landlord_code);
create index idx_cb_returns_summary_property      on cb_returns_summary (property_code);
create index idx_cb_returns_summary_period        on cb_returns_summary (year, month);
create index idx_cb_returns_summary_status        on cb_returns_summary (return_status, paid_status);


-- ============================================================================
-- 2. cb_returns_clients  (source: CHRTXS — 1,470,210 rows)
-- ============================================================================
-- Each row is a detail/charge line within a return — per unit, per tenant,
-- per charge type. Links to cb_returns_summary via return_code (RETURNID).
-- Includes both actual charges (rent, water, service charge) and deductions
-- (commission, VAT, recoveries).

create table cb_returns_clients (
    id                    bigint generated by default as identity primary key,
    return_code           varchar(50) not null,      -- RETURNID: FK to cb_returns_summary
    return_period         int,                       -- RETNPRD: period YYYYMM (int)
    transaction_number    varchar(12) not null,      -- TRANSNUM: unique line transaction number
    transaction_date      varchar(50),               -- TRANSDAT: transaction date (varchar in source)
    transaction_date_num  numeric(18,0),             -- TRANSDATF: date as numeric
    entry_description     varchar(100),              -- ENTRYDE: entry type description
    entry_type            varchar(100),              -- ENTRYTYP: charge type (RENT, Commission, etc.)
    transaction_code      varchar(50),               -- TRANSCODE: transaction code
    narration             varchar(200),              -- ENTRYDESC: full narration
    transaction_ref       varchar(100),              -- TRANSREF: transaction reference
    source_date           timestamp,                 -- SRCDATE: source/origin date
    property_code         varchar(50),               -- BLOCKID: property/block code
    unit_code             varchar(50),               -- UNITNO: unit number
    unit_seq_id           int,                       -- UNITID: unit sequence id
    dr_cr                 varchar(3),                -- DRCR: debit/credit indicator
    tenant_name           varchar(50),               -- TENNAME: tenant name
    tenant_status         varchar(50),               -- TENSTAT: tenant status
    amount_text           varchar(50),               -- ENTAMTT: amount as text
    amount_payable_landlord numeric(18,2) default 0, -- AMTPAYBL: landlord payable amount
    amount_payable_tenant numeric(18,2) default 0,   -- AMTPAYTN: tenant payment amount
    residual_debit        numeric(18,2) default 0,   -- RESAMTDR: residual debit
    residual_credit       numeric(18,2) default 0,   -- RESAMTCR: residual credit
    net_amount            numeric(18,2) default 0,   -- RESAMTNT: net/gross amount
    remarks               varchar(50),               -- TREMARKS: transaction remarks
    transaction_source    varchar(50),               -- TRANSSRC: source of transaction
    deduction_point       int,                       -- DEDPNT: deduction point
    is_vatable            varchar(3),                -- VATABL: VAT applicable (Yes/No)
    is_commissionable     varchar(3),                -- COMMBL: commissionable (Yes/No)
    deduction_point_2     varchar(50),               -- DEDPNT2: secondary deduction point
    payment_period        int,                       -- PPERIOD: payment period
    cheque_number         varchar(50),               -- CHQNO: cheque number
    bank_account          varchar(50),               -- BANKACC: bank account
    vat_amount            numeric(18,0) default 0,   -- VATAMT: VAT amount
    auth_2m               int default 0,             -- AUTH2M: authorization flag
    auth_un               int default 0,             -- AUTHUN: authorization flag
    pay_percentage        varchar(50),               -- PAYPERC: pay percentage
    return_line_id        int,                       -- PRE-STAMPED: return_line_id
    property_id           int,                       -- PRE-STAMPED: FK sys_pm_properties
    client_id             int,                       -- PRE-STAMPED: FK sys_pm_clients (landlord)
    zone_id               int,                       -- PRE-STAMPED: FK sys_set_zones
    field_officer_id      int,                       -- PRE-STAMPED: FK sys_staff (FO)
    zone_supervisor_id    int,                       -- PRE-STAMPED: FK sys_staff (supervisor)
    zone_manager_id       int,                       -- PRE-STAMPED: FK sys_staff (manager)
    unit_id               int,                       -- PRE-STAMPED: FK sys_pm_units
    tenant_id             int,                       -- PRE-STAMPED: FK sys_pm_clients (tenant)
    return_id             int,                       -- PRE-STAMPED: FK cb_returns_summary
    invoice_id            int                        -- PRE-STAMPED: FK sys_pm_debtors_invoices
);

create index idx_cb_returns_clients_return    on cb_returns_clients (return_code);
create index idx_cb_returns_clients_property  on cb_returns_clients (property_id);
create index idx_cb_returns_clients_tenant    on cb_returns_clients (tenant_id);
create index idx_cb_returns_clients_unit      on cb_returns_clients (unit_id);
create index idx_cb_returns_clients_period    on cb_returns_clients (return_period);
create index idx_cb_returns_clients_type      on cb_returns_clients (entry_type);


-- ============================================================================
-- 3. cb_landlord_account  (source: CHLACC — 128,423 rows)
-- ============================================================================
-- Landlord account ledger. Each row is a debit or credit entry on a landlord's
-- account for a given property. Entries come from returns (RETURNID link),
-- direct charges, payments, bank fees, refunds, etc.
--
-- Top ENTRYID codes:
--   0005 (28,814) = RETURNS — return posting
--   0014 (16,895) = CANCELLED CHEQUE CHARGES
--   0006 (16,874) = GARBAGE PAYMENTS
--   0019 (13,415) = BANKING SERVICES
--   0009 (12,299) = AGENT FEES
--   0015 ( 3,706) = CARETAKER SALARY
--   0003 ( 2,952) = WATER BILL (2nd instalment)
--   0004 ( 2,896) = WATER BILL CHARGE
--   0002 ( 2,660) = ELECTRICITY BILL CHARGE
--   0001 ( 2,718) = ELECTRICITY BILL (1st cheque)
--   0013 ( 5,706) = REFUND OF DEPOSIT
--   0020 ( 2,443) = LOAN

create table cb_landlord_account (
    id                    bigint generated by default as identity primary key,
    year                  int,                       -- YEARR: transaction year
    month                 int,                       -- MONTHH: transaction month
    landlord_code         varchar(20),               -- LORDID: landlord code
    landlord_name         varchar(60),               -- LFNAME: landlord full name
    property_code         varchar(20),               -- HOUSEID: property/house code
    transaction_number    varchar(50) not null,       -- GTTCNUM: unique transaction number
    entry_type_code       varchar(20),               -- ENTRYID: entry type code (0001-0046+)
    entry_sequence        int,                       -- ENTRYNU: entry sequence number
    entry_description     varchar(250),              -- ENTRYDE: entry description/narration
    entry_date            timestamp,                 -- ENTRYDA: entry date
    debit_amount          numeric(18,2) default 0,   -- AMTDR: debit amount
    credit_amount         numeric(18,0) default 0,   -- AMTCR: credit amount
    total_amount          numeric(10,2) default 0,   -- AMTTOT: running total
    account_status        int default 0,             -- ACCSTAT: account status
    payment_ref           varchar(25),               -- PAYREF: payment reference
    payment_ref_type      varchar(20),               -- PAYREFT: payment reference type
    interest_rate         numeric(18,2) default 0,   -- INTRATE: interest rate
    audit_user            varchar(20),               -- AUDTUSR: audit user / created by
    entry_particulars     varchar(200),              -- ENTPART: entry particulars
    pv_number             varchar(20),               -- PVNO: payment voucher number
    gl_account            varchar(50),               -- FINACC: GL account code
    vendor_id             varchar(50),               -- VENDORID: vendor identifier
    is_recovered          int default 0,             -- RECOVD: recovery flag (0/1)
    recovery_year         int,                       -- RECOYR: recovery year
    recovery_month        int,                       -- RECOMN: recovery month
    return_transaction    varchar(50),               -- RETTRANS: return transaction ref
    return_code           varchar(50),               -- RETURNID: FK to cb_returns_summary
    client_id             int,                       -- PRE-STAMPED: FK sys_pm_clients (landlord)
    property_id           int                        -- PRE-STAMPED: FK sys_pm_properties
);

create index idx_cb_landlord_acct_landlord    on cb_landlord_account (landlord_code);
create index idx_cb_landlord_acct_property    on cb_landlord_account (property_id);
create index idx_cb_landlord_acct_client      on cb_landlord_account (client_id);
create index idx_cb_landlord_acct_period      on cb_landlord_account (year, month);
create index idx_cb_landlord_acct_entry_type  on cb_landlord_account (entry_type_code);
create index idx_cb_landlord_acct_return      on cb_landlord_account (return_code);
create index idx_cb_landlord_acct_txnum       on cb_landlord_account (transaction_number);
